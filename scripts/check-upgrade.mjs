import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import dbModule from '../services/db/sqlite.js';
import ragModule from '../services/rag/index.js';
import memoryModule from '../services/memory/index.js';

const fixtureDir = fs.mkdtempSync(path.join(os.tmpdir(), 'studyagent-upgrade-'));
const fixtureFile = path.join(fixtureDir, 'test.sqlite');
let db = dbModule.createLearningDb(fixtureFile);
db.ensureBootstrap({ documents: [] });
try {
  const workspace = db.createWorkspace('Upgrade regression');
  const conversation = db.upsertConversation({ title: 'Recent messages', workspaceId: workspace.id });
  for (let i = 0; i < 12; i++) db.saveConversationMessage({ conversationId: conversation.id, role: i % 2 ? 'assistant' : 'user', content: `turn-${i}` });
  assert.deepEqual(db.listConversationMessages(conversation.id, 4).map(m => m.content), ['turn-8', 'turn-9', 'turn-10', 'turn-11'], 'limited history must return the newest messages in chronological order');
  db.upsertDocument({ document: { id: 'doc-test', title: '数值算法', fileType: 'MD', createdAt: new Date().toISOString() }, sections: [{ id: 'section-test', title: '条件数', content: '矩阵条件数描述扰动的敏感性。', position: 0, locator: { page: 2 } }], chunks: [{ id: 'chunk-test', sectionId: 'section-test', content: '矩阵条件数描述扰动的敏感性。', chunkIndex: 0 }] });
  const chunks = db.getDocumentContext('doc-test');
  const rag = ragModule.createRagService(db);
  await rag.indexChunksWithProvider(chunks, async () => ({ model: 'external-test', embeddings: [[1, 0, 1]] }));
  rag.indexChunks(chunks);
  assert.equal(db.getEmbeddings(['chunk-test'])[0].model, 'external-test', 'startup must not overwrite a remote index');
  const hits = rag.context('请解释条件数的作用', { documentIds: ['doc-test'] });
  assert.equal(hits[0]?.chunkId, 'chunk-test', 'Chinese query must find the original chunk and retain a precise source id');
  assert.equal(hits[0]?.retrievalMode, 'local-hash-fallback', 'remote vectors must not be compared with a local query vector');
  await assert.rejects(rag.indexChunksWithProvider(chunks, async () => ({ model: 'bad', embeddings: [[NaN, 1]] })), /invalid/i);
  assert.equal(db.getEmbeddings(['chunk-test'])[0].model, 'external-test', 'invalid vectors must not replace the good index');
  assert.throws(() => rag.indexChunks(chunks, { model: 'wrong-model', vectors: [[1,2]] }), /invalid/);
  assert.equal(db.getEmbeddings(['chunk-test'])[0].model, 'external-test');
  const annotations = db.saveAnnotation({ documentId: 'doc-test', page: 2, text: '条件数', note: '没有理解' });
  db.updateAnnotation(annotations.id, { note: '考试重点' });
  assert.equal(db.listLearningEvents({ documentId: 'doc-test' }).filter(e => e.event_type === 'annotation').length, 1);
  assert.equal(db.listLearningEvents({ documentId: 'doc-test' })[0].evidence.note, '考试重点');
  const session = db.startLearningSession({ documentId: 'doc-test' });
  db.updateLearningSession(session.id, { pagesViewed: [1, 2] });
  db.updateLearningSession(session.id, { pagesViewed: [2] });
  db.updateLearningSession(session.id, { pagesViewed: [0, -1, 1.5, null] });
  db.updateLearningSession(session.id, { pagesViewed: [1], currentPage: 1 });
  assert.equal(db.getReadingPosition('doc-test').currentPage, 1);
  assert.equal(db.getReadingPosition('doc-test').progress, 1);
  assert.equal(db.listLearningEvents({ documentId: 'doc-test' }).filter(e => e.event_type === 'reading').length, 2, 'page events are idempotent within a session');
  const memory = memoryModule.createMemoryService(db);
  for (let i = 0; i < 20; i++) memory.recordInteraction({ question: '什么是条件数？', answer: 'Condition Number measures sensitivity.', documentId: 'doc-test' });
  const concept = db.listConcepts().find(c => c.name === 'Condition Number');
  assert.equal(concept.masteryScore, 0, 'asking repeatedly cannot manufacture mastery');
  assert.equal(db.getMasteryEvidence(concept.id).score, null);
  assert.equal(db.getMasteryEvidence(concept.id).label, 'Low Evidence');
  memory.recordReview({ concept: 'Condition Number', correct: true });
  assert.equal(db.getMasteryEvidence(concept.id).label, 'Developing');
  assert.ok(db.getMasteryEvidence(concept.id).confidence < 0.2);
  const count = db.listLearningEvents({ limit: 1000 }).length;
  memory.recordInteraction({ question: '私密问题', answer: '私密回答', optedOut: true });
  assert.equal(db.listLearningEvents({ limit: 1000 }).length, count);
  const userB = db.createUserAccount({ email: 'other@regression.local', username: 'Other' });
  db.setUserId(userB.id);
  assert.equal(db.listLearningEvents().length, 0);
  assert.equal(db.listChapters().length, 0);
  assert.throws(() => db.recordLearningEvent({ type: 'annotation', sourceId: 'foreign', documentId: 'doc-test' }), /不属于/);
  db.setUserId('user-local');
  db.upsertDocument({ document: { id: 'heading-doc', title: 'Heading notes', fileType: 'MD' }, sections: [{ id: 'heading', title: '第一章', content: '定义', kind: 'heading', locator: { headingLevel: 2 } }], chunks: [] });
  assert.equal(db.listChapters({ documentId: 'heading-doc' })[0].level, 2);
  assert.throws(() => db.upsertDocument({ document: { id: 'heading-doc', title: 'Broken replacement' }, sections: [{ id: 'duplicate' }, { id: 'duplicate' }] }), /UNIQUE/);
  assert.equal(db.getDocument('heading-doc').title, 'Heading notes', 'failed parsing persistence must rollback the entire replacement');
  assert.equal(db.listChapters({ documentId: 'heading-doc' }).length, 1);
  db.deleteAnnotation(annotations.id);
  assert.ok(!db.listLearningEvents().some(e => e.source_id === annotations.id), 'deleting a source annotation must remove its event');
  assert.equal(db.database.prepare('SELECT COUNT(*) count FROM schema_migrations').get().count, 3);
  db.close();
  db = null;
  db = dbModule.createLearningDb(fixtureFile);
  assert.deepEqual(db.migrationResult.applied, [], 'reopening must not reapply a migration');
  assert.equal(db.getDocument('heading-doc').title, 'Heading notes');
  assert.equal(db.getReadingPosition('doc-test').currentPage, 1, 'last actual page must survive database reopen');
  assert.deepEqual(db.getReadingPosition('doc-test').pagesViewed, [1,2]);
  const unchanged = db.getDocument('doc-test');
  db.upsertDocument({ document: unchanged, sections: [{ id: 'section-test', title: '条件数', locator: { page: 2 } }] });
  assert.equal(db.getReadingPosition('doc-test').currentPage, 1, 'reprocessing a document must not erase reading progress');
  // Only this disposable fixture is reduced to the pre-v1 schema to exercise real upgrade/backups.
  db.database.exec('DROP TABLE reading_positions; DROP TABLE document_import_jobs; ALTER TABLE prompt_optimization_logs DROP COLUMN optimization_json; DROP TABLE learning_events; DROP TABLE chapters; DROP INDEX knowledge_cards_category; ALTER TABLE knowledge_cards DROP COLUMN category; ALTER TABLE knowledge_cards DROP COLUMN card_type; ALTER TABLE knowledge_cards DROP COLUMN content_json; DROP TABLE schema_migrations; DROP INDEX messages_recent');
  db.close();
  db = null;
  db = dbModule.createLearningDb(fixtureFile);
  assert.deepEqual(db.migrationResult.applied, [1, 2, 3]);
  assert.ok(fs.existsSync(db.migrationResult.backupPath));
  const backup = new DatabaseSync(db.migrationResult.backupPath, { readOnly: true });
  try {
    assert.equal(backup.prepare('PRAGMA integrity_check').get().integrity_check, 'ok');
    assert.equal(backup.prepare("SELECT title FROM documents WHERE id='heading-doc'").get().title, 'Heading notes');
  } finally { backup.close(); }
  assert.equal(db.listChapters({ documentId: 'heading-doc' }).length, 1, 'existing headings must be backfilled without losing documents');
  assert.equal(db.getDocument('doc-test').title, '数值算法');
  console.log('PASS: recent conversation, Chinese retrieval, embedding-space isolation, index preservation, invalid vector rejection, chunk citations');
  console.log('PASS: versioned migration, restart idempotency, backup integrity, heading backfill, atomic document replacement, learning evidence, opt-out, user isolation, conservative mastery');
} catch (error) {
  console.error('Upgrade regression root cause:', error);
  throw error;
} finally {
  db?.close();
  fs.rmSync(fixtureDir, { recursive: true, force: true });
}
